import fs from 'fs'
import os from 'os'
import path from 'path'
import { afterEach, describe, expect, it } from 'vitest'
import { CliError } from '../../src/errors'
import { Logger } from '../../src/logger'
import { ProjectService } from '../../src/services/project.service'

const dirs: string[] = []

function tmpDir(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'nec-project-'))
  dirs.push(dir)
  return dir
}

function warnings(): { logger: Logger; messages: string[] } {
  const messages: string[] = []
  const logger: Logger = {
    info: () => undefined,
    success: () => undefined,
    warn: (message: string) => messages.push(message),
    error: () => undefined,
  }

  return { logger, messages }
}

function manifest(cwd: string): { version: number; generated: Record<string, string> } {
  return JSON.parse(fs.readFileSync(path.join(cwd, '.nec/manifest.json'), 'utf-8'))
}

afterEach(() => {
  for (const dir of dirs.splice(0)) {
    fs.rmSync(dir, { recursive: true, force: true })
  }
})

describe('ProjectService', () => {
  it('writes a new file and records its hash in the manifest', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)

    const result = project.write('src/utils/a.ts', 'export const a = 1\n')

    expect(result.status).toBe('created')
    expect(project.read('src/utils/a.ts')).toBe('export const a = 1\n')
    expect(manifest(cwd).version).toBe(1)
    expect(manifest(cwd).generated['src/utils/a.ts']).toMatch(/^sha256:[a-f0-9]{64}$/)
  })

  it('does not rewrite an unchanged generated file', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)

    project.write('src/a.ts', 'a\n')
    const stat = fs.statSync(path.join(cwd, 'src/a.ts'))

    const second = project.write('src/a.ts', 'a\n')

    expect(second.status).toBe('skipped')
    expect(second.reason).toBe('up-to-date')
    expect(fs.statSync(path.join(cwd, 'src/a.ts')).mtimeMs).toBe(stat.mtimeMs)
  })

  it('preserves a file modified by the user and warns about --force', () => {
    const cwd = tmpDir()
    const { logger, messages } = warnings()
    const project = new ProjectService(cwd, { logger })

    project.write('src/a.ts', 'generated\n')
    fs.writeFileSync(path.join(cwd, 'src/a.ts'), 'custom\n')

    const result = project.write('src/a.ts', 'generated\n')

    expect(result.status).toBe('skipped')
    expect(result.reason).toBe('modified by the user')
    expect(fs.readFileSync(path.join(cwd, 'src/a.ts'), 'utf-8')).toBe('custom\n')
    expect(messages.join('\n')).toContain('--force')
  })

  it('overwrites a modified file with --force', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd, { force: true })

    project.write('src/a.ts', 'generated\n')
    fs.writeFileSync(path.join(cwd, 'src/a.ts'), 'custom\n')

    const result = project.write('src/a.ts', 'generated\n')

    expect(result.status).toBe('overwritten')
    expect(fs.readFileSync(path.join(cwd, 'src/a.ts'), 'utf-8')).toBe('generated\n')
  })

  it('does not overwrite a file that is not in the manifest', () => {
    const cwd = tmpDir()
    const { logger, messages } = warnings()
    const project = new ProjectService(cwd, { logger })
    fs.mkdirSync(path.join(cwd, 'src'), { recursive: true })
    fs.writeFileSync(path.join(cwd, 'src/a.ts'), 'user file\n')

    const result = project.write('src/a.ts', 'generated\n')

    expect(result.status).toBe('skipped')
    expect(result.reason).toBe('not generated by the CLI')
    expect(messages.join('\n')).toContain('not generated by the CLI')
  })

  it('adopts an identical existing file without warning', () => {
    const cwd = tmpDir()
    const { logger, messages } = warnings()
    const project = new ProjectService(cwd, { logger })
    fs.mkdirSync(path.join(cwd, 'src'), { recursive: true })
    fs.writeFileSync(path.join(cwd, 'src/a.ts'), 'generated\n')

    const result = project.write('src/a.ts', 'generated\n')

    expect(result.status).toBe('skipped')
    expect(manifest(cwd).generated['src/a.ts']).toBeDefined()
    expect(messages).toEqual([])
  })

  it('fails when a create-policy file already exists', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    project.write('src/a.ts', 'generated\n', 'create')

    expect(() => project.write('src/a.ts', 'other\n', 'create')).toThrow(CliError)

    try {
      project.write('src/a.ts', 'other\n', 'create')
    } catch (error) {
      expect((error as CliError).hint).toContain('--force')
    }
  })

  it('overwrites a create-policy file with --force', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    project.write('src/a.ts', 'first\n', 'create')

    const forced = new ProjectService(cwd, { force: true })
    const result = forced.write('src/a.ts', 'second\n', 'create')

    expect(result.status).toBe('overwritten')
    expect(forced.read('src/a.ts')).toBe('second\n')
  })

  it('requires --force for the overwrite policy', () => {
    const cwd = tmpDir()
    const { logger, messages } = warnings()
    const project = new ProjectService(cwd, { logger })
    project.write('src/a.ts', 'first\n')

    const skipped = project.write('src/a.ts', 'second\n', 'overwrite')
    expect(skipped.status).toBe('skipped')
    expect(messages.join('\n')).toContain('--force')

    const forced = new ProjectService(cwd, { force: true })
    expect(forced.write('src/a.ts', 'second\n', 'overwrite').status).toBe('overwritten')
  })

  it('skips files with the skip policy without touching them', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    fs.mkdirSync(path.join(cwd, 'src'), { recursive: true })
    fs.writeFileSync(path.join(cwd, 'src/a.ts'), 'keep\n')

    const result = project.write('src/a.ts', 'generated\n', 'skip')

    expect(result.status).toBe('skipped')
    expect(result.reason).toBe('exists')
    expect(project.read('src/a.ts')).toBe('keep\n')
  })

  it('copies a template file and a template directory', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)

    project.copy('src/utils/mailer.ts', 'generator/common/mailer/mailer.ts')
    const results = project.copyDir('src/templates', 'generator/common/mailer/templates')

    expect(project.exists('src/utils/mailer.ts')).toBe(true)
    expect(results.length).toBeGreaterThan(0)
    expect(project.exists('src/templates/notification/notification.hbs')).toBe(true)
    expect(project.exists('src/templates/notification/logo.png')).toBe(true)
  })

  it('removes files and their manifest entries', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    project.write('src/a.ts', 'a\n')

    project.remove('src/a.ts')

    expect(project.exists('src/a.ts')).toBe(false)
    expect(manifest(cwd).generated['src/a.ts']).toBeUndefined()
  })

  it('rejects paths outside the project', () => {
    const project = new ProjectService(tmpDir())

    expect(() => project.write('../evil.ts', 'x')).toThrow(CliError)
    expect(() => project.write('/tmp/evil.ts', 'x')).toThrow(CliError)
  })

  it('preflights a group of create paths before writing any of them', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    project.write('src/a.ts', 'a\n', 'create')

    expect(() => project.assertCanCreate(['src/a.ts', 'src/b.ts'])).toThrow(CliError)
    expect(project.exists('src/b.ts')).toBe(false)
  })

  it('reports every existing file in the preflight error', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    project.write('src/a.ts', 'a\n', 'create')
    project.write('src/b.ts', 'b\n', 'create')

    try {
      project.assertCanCreate(['src/a.ts', 'src/b.ts', 'src/c.ts'])
      throw new Error('expected assertCanCreate to throw')
    } catch (error) {
      expect(error).toBeInstanceOf(CliError)
      expect((error as CliError).message).toContain('src/a.ts')
      expect((error as CliError).message).toContain('src/b.ts')
      expect((error as CliError).message).not.toContain('src/c.ts')
      expect((error as CliError).hint).toContain('--force')
    }
  })

  it('skips the create preflight with --force', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)
    project.write('src/a.ts', 'a\n', 'create')

    const forced = new ProjectService(cwd, { force: true })

    expect(() => forced.assertCanCreate(['src/a.ts', 'src/b.ts'])).not.toThrow()
  })

  it('detects a generated project', () => {
    const cwd = tmpDir()
    const project = new ProjectService(cwd)

    expect(project.isProject()).toBe(false)

    fs.writeFileSync(path.join(cwd, 'cli.config.json'), '{}')
    fs.writeFileSync(path.join(cwd, 'package.json'), '{}')

    expect(project.isProject()).toBe(true)
  })

  it('resolves a service for a subdirectory and keeps --force', () => {
    const root = tmpDir()
    const project = new ProjectService(root, { force: true })

    expect(project.forDirectory('app').cwd).toBe(path.join(root, 'app'))
    expect(project.forDirectory('app').write('src/a.ts', 'a\n', 'create').status).toBe('created')
  })
})
